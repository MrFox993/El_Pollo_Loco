
/**
 * Represents keyboard input states for character control.
 */
class Keyboard {
    /** @type {boolean} */ left = false;
    /** @type {boolean} */ right = false;
    /** @type {boolean} */ up = false;
    /** @type {boolean} */ down = false;
    /** @type {boolean} */ space = false;
    /** @type {boolean} */ c = false;
    /** @type {boolean} */ m = false;
    /** @type {boolean} */ p = false;
}